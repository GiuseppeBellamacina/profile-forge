#!/usr/bin/env node
// Writes TROPHIES.md: every trophy, what earns it and how it looks. Generated from the same tables the card uses (src/stats.js, src/secrets.js),
// so it never drifts. The pictures come from scripts/gen-docs.js (docs/guide/trophies-*.png).
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SECRETS, SECRET_GROUPS } from "../src/secrets.js";
import { trophyTable } from "../src/stats.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const UNITS = { stars: "stars", commits: "commits", followers: "followers", prs: "pull requests", repos: "repositories", issues: "issues", reviews: "reviews", experience: "years on GitHub" };
// Experience is counted in days / 100 in the table; the card shows years
const need = (t, min) => (t.key === "experience" ? `~${Math.round((min * 100) / 365.25)} years` : `${min}+ ${UNITS[t.key]}`);

let md = `# Trophy guide

<!-- generated by scripts/gen-trophy-guide.js, do not edit by hand -->

Every trophy the card can show. There are two kinds:

- **Level trophies** are the classic cup, in the colour of the level you reached. They are always there (the \`?\` cup means you have not reached the first level yet).
- **Secret trophies** are cut gems with their own glyph. They appear **only once earned** and never show a level. Hover one in a browser to read how it was earned.

Both live in the same panel and follow the same options (see [Trophies](GUIDE.md#trophies) in the guide).

## Level trophies

<img src="docs/guide/trophies-levels.png">

One cup per level, from **E** (first steps) up to **SSS**, with the steps in between (E, E+, D-, D, D+ … S-, S, S+): **A** adds the laurel, **S-** and **S** a second cup, **S+** a third, and **SSS** a pulsing frame and a light that sweeps across. The table lists the thresholds of the letters; the `+` / `-` steps sit evenly between them. The level colours are the same as the header rank (\`levelE\` … \`levelTop\` in \`colors\`).

`;
for (const t of trophyTable()) {
  md += `### ${t.title}${t.optional ? " (opt-in)" : ""}\n\n${t.optional ? `Not shown by default: add \`"${t.title}"\` to \`trophies.extra\`.\n\n` : ""}| Level | Needs | Name |\n|---|---|---|\n`;
  for (const l of t.levels) md += `| ${l.level} | ${need(t, l.min)} | ${l.label} |\n`;
  md += "\n";
}
md += `Filter them with \`titles\` / \`hideTitles\` (aliases such as \`Star\`, \`Commit\`, \`PR\`, \`Repo\`, \`Review\` and \`Duration\` work) or by level with \`ranks\` / \`hideRanks\`.

## Secret trophies

${SECRETS.length} of them. They are only drawn when earned; \`ranks: ["SECRET"]\` shows just these and \`hideRanks: ["SECRET"]\` hides them all. Each has a **Title** you can pass to \`titles\` / \`hideTitles\`.

<img src="docs/guide/trophies-secret-all.png">
`;
const first = (t) => SECRETS.findIndex((d) => d.title === t);
const bounds = SECRET_GROUPS.map(([, t]) => first(t)).concat(SECRETS.length);
const NOTES = {
  "Days of the year": "These look at the whole contribution calendar, any year. **Happy Birthday!** is the exception: it shows on your birthday, which you set in the config with `trophies.birthday` (`\"MM-DD\"` or `\"YYYY-MM-DD\"`, in the card's `timezone`). Without it the trophy never appears.",
  "People and platform": "The badges (GitHub Star, Campus Expert, Bounty Hunter, Dev Program, Hubber), sponsors, gists, following and starred counts come from your public profile. Sharpshooter and Answer Machine use the merged-PR and discussion counts, which are fetched only when the card shows one of those stats.",
  Special: "A special trophy has a pulsing frame and a `FRIEND` tag instead of `SECRET`. **Forge Friend** is for friends of the author of profile-forge: you and [GiuseppeBellamacina](https://github.com/GiuseppeBellamacina) follow each other on GitHub (checked on github.com only).",
};
SECRET_GROUPS.forEach(([name], g) => {
  md += `\n### ${name}\n\n<img src="docs/guide/trophies-secret-${g + 1}.png">\n\n${NOTES[name] ? NOTES[name] + "\n\n" : ""}| Title | Shown as | Earned by |\n|---|---|---|\n`;
  for (const d of SECRETS.slice(bounds[g], bounds[g + 1])) md += `| \`${d.title}\` | ${d.label} | ${cap(d.hint)} |\n`;
});
writeFileSync(join(root, "TROPHIES.md"), md);
console.log("wrote TROPHIES.md");
