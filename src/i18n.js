const DICTS = { en, it, es, fr, de, "pt-br": ptbr, ja, zh };
export const LOCALES = Object.keys(DICTS);

/** Normalize "pt_BR" / "PT-br" -> "pt-br"; unknown locales throw. */
export function normLocale(l = "en") {
  const k = String(l).toLowerCase().replace("_", "-");
  if (!DICTS[k])
    throw new Error(`Unknown locale "${l}". Available: ${LOCALES.join(", ")}`);
  return k;
}

/** Translator for a locale: tr("inYear", { n: 5, y: 2026 }). */
export const translator =
  (locale) =>
  (key, vars = {}) =>
    (DICTS[locale]?.[key] ?? en[key] ?? key).replace(
      /\{(\w+)\}/g,
      (_, v) => vars[v] ?? "",
    );

/** BCP-47 tag for Intl. */
export const intlTag = (locale) => (locale === "pt-br" ? "pt-BR" : locale);
